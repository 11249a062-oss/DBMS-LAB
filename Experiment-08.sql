CREATE TABLE STUDENT_COURSE_1NF (
    STUDENT_ID NUMBER(5),
    STUDENT_NAME VARCHAR2(30),
    COURSE_ID NUMBER(5),
    COURSE_NAME VARCHAR2(40),
    CONSTRAINT PK_SC1NF PRIMARY KEY (STUDENT_ID, COURSE_ID)
);
CREATE TABLE STUDENT_INFO (STUDENT_ID NUMBER(5) PRIMARY KEY, STUDENT_NAME VARCHAR2(30));
CREATE TABLE COURSE_INFO (COURSE_ID NUMBER(5) PRIMARY KEY, COURSE_NAME VARCHAR2(40));
CREATE TABLE STUDENT_COURSE (
    STUDENT_ID NUMBER(5),
    COURSE_ID NUMBER(5),
    CONSTRAINT PK_STUDENT_COURSE PRIMARY KEY (STUDENT_ID, COURSE_ID),
    CONSTRAINT FK_SC_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT_INFO(STUDENT_ID),
    CONSTRAINT FK_SC_COURSE FOREIGN KEY (COURSE_ID) REFERENCES COURSE_INFO(COURSE_ID)
);
