SET SERVEROUTPUT ON;
DECLARE
BEGIN
    UPDATE STUDENT SET MARKS = MARKS + 1 WHERE STUDENT_ID = 101;
    DBMS_OUTPUT.PUT_LINE('Rows updated: ' || SQL%ROWCOUNT);
END;
/
DECLARE
    CURSOR C_STUDENTS IS SELECT STUDENT_ID, STUDENT_NAME, MARKS FROM STUDENT;
    V_ID STUDENT.STUDENT_ID%TYPE;
    V_NAME STUDENT.STUDENT_NAME%TYPE;
    V_MARKS STUDENT.MARKS%TYPE;
BEGIN
    OPEN C_STUDENTS;
    LOOP
        FETCH C_STUDENTS INTO V_ID, V_NAME, V_MARKS;
        EXIT WHEN C_STUDENTS%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE(V_ID || ' ' || V_NAME || ' ' || V_MARKS);
    END LOOP;
    CLOSE C_STUDENTS;
END;
/
BEGIN
    FOR R IN (SELECT STUDENT_ID, STUDENT_NAME, MARKS FROM STUDENT) LOOP
        DBMS_OUTPUT.PUT_LINE(R.STUDENT_ID || ' ' || R.STUDENT_NAME || ' ' || R.MARKS);
    END LOOP;
END;
/
