SET SERVEROUTPUT ON;
DECLARE
    V_RESULT NUMBER;
BEGIN
    V_RESULT := 10 / 0;
EXCEPTION
    WHEN ZERO_DIVIDE THEN DBMS_OUTPUT.PUT_LINE('Error: division by zero');
    WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('Unexpected error: ' || SQLERRM);
END;
/
DECLARE
    V_NAME STUDENT.STUDENT_NAME%TYPE;
BEGIN
    SELECT STUDENT_NAME INTO V_NAME FROM STUDENT WHERE STUDENT_ID = -1;
EXCEPTION
    WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('No student found');
    WHEN TOO_MANY_ROWS THEN DBMS_OUTPUT.PUT_LINE('More than one student found');
END;
/
