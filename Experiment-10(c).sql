CREATE OR REPLACE PROCEDURE SHOW_STUDENT_DETAILS (P_ID IN NUMBER) AS
    V_NAME STUDENT.STUDENT_NAME%TYPE;
    V_MARKS STUDENT.MARKS%TYPE;
BEGIN
    SELECT STUDENT_NAME, MARKS INTO V_NAME, V_MARKS FROM STUDENT WHERE STUDENT_ID = P_ID;
    DBMS_OUTPUT.PUT_LINE('Name: ' || V_NAME || ', Marks: ' || V_MARKS);
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('Student not found');
END;
/
BEGIN
    SHOW_STUDENT_DETAILS(101);
END;
/
CREATE OR REPLACE FUNCTION FIND_GRADE (P_MARKS IN NUMBER) RETURN VARCHAR2 IS
BEGIN
    IF P_MARKS >= 90 THEN RETURN 'A';
    ELSIF P_MARKS >= 80 THEN RETURN 'B';
    ELSIF P_MARKS >= 70 THEN RETURN 'C';
    ELSE RETURN 'D';
    END IF;
END;
/
SELECT STUDENT_NAME, MARKS, FIND_GRADE(MARKS) AS GRADE FROM STUDENT;
