CREATE TABLE EMPLOYEE (EMP_ID NUMBER(5) PRIMARY KEY, EMP_NAME VARCHAR2(30), SALARY NUMBER(8));
CREATE TABLE EMP_AUDIT (EMP_ID NUMBER(5), ACTION_NAME VARCHAR2(10), ACTION_DATE DATE);
INSERT INTO EMPLOYEE VALUES (1, 'ARUN', 35000);
CREATE OR REPLACE TRIGGER TRG_EMP_INSERT AFTER INSERT ON EMPLOYEE FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT VALUES (:NEW.EMP_ID, 'INSERT', SYSDATE);
END;
/
CREATE OR REPLACE TRIGGER TRG_EMP_UPDATE AFTER UPDATE ON EMPLOYEE FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT VALUES (:NEW.EMP_ID, 'UPDATE', SYSDATE);
END;
/
CREATE OR REPLACE TRIGGER TRG_EMP_DELETE AFTER DELETE ON EMPLOYEE FOR EACH ROW
BEGIN
    INSERT INTO EMP_AUDIT VALUES (:OLD.EMP_ID, 'DELETE', SYSDATE);
END;
/
